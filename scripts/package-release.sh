#!/usr/bin/env bash
# The composite package assembly + the signing chain (D2/D5/D7): ONE tarball per suite tag,
# everything the clinic's verified bytes need — the suite's tag tree (the bootstrap, the host CLI,
# the provisionador, the executor tree, the theme, the data masters, the sites register) overlaid at
# identical paths (D11) with the old gestion's release-frozen provisioning/apps (VENDOR + tarballs)
# until #42 — the layout step_descargar's VENDOR loop and provisionador's ASSETS already read.
#
# WHAT IT PRODUCES (all in --out):
#   apsconecta-<tag>.tar.gz      the composite; package root instalador/ (install.sh's contract)
#   SHA256SUMS                   one line: <sha256>  apsconecta-<tag>.tar.gz (install.sh greps -qx it)
#   SHA256SUMS.minisig           signify-openbsd (minisign-format) signature over SHA256SUMS
#   apsconecta-<tag>-install.sh  install.sh with BUNDLE_TAG + TARBALL_SHA256 filled (the one-liner)
#
# THE TRUST CHAIN (D7): Ed25519 over SHA256SUMS, made and PROVEN here with the same apt
# signify-openbsd the clinic verifies with — a format incompatibility reds CI, never a clinic.
# The tag binds through the SIGNED BYTES: SHA256SUMS names apsconecta-<tag>.tar.gz, so a
# signature that verifies is a signature for that tag's package. (signify has NO signed trusted
# comment — that is minisign's -t; signify's -t is keytype, silently ignored at -S — so the
# .minisig's comment line is rewritten to name the tag for humans; verification never reads it.)
# The key never reaches argv or a URL (P45): MINISIGN_SECRET_KEY (the .sec file's contents)
# lands in a 0600 trap-removed temp file; MINISIGN_KEY_PASSWORD rides stdin — signify's own
# headless path (a non-tty stdin makes kdf() read the passphrase from stdin; source-verified in
# portable signify.c). A passphrase-less key (signify -G -n) signs with the same call, empty pipe.
#
# DETERMINISM (the house git-archive discipline, one step wider): the tag tree comes from
# `git archive` (never a working tree — a dirty checkout cannot leak into a package), and every
# member is re-tarred with --sort=name, the tag commit's unix mtime, root:0 ownership and
# gzip -n — any clone of the tag rebuilds the same bytes (the self-test asserts two passes, one
# sha256).
#
# COUNTED BEFORE CHECKED, everywhere (the silent-green rule): one register CSV, one VENDOR per
# apps.json row and no other app dir, VERSION == tag, host/aps-conecta present, installer.pub's key
# line == install.sh's SIGNIFY_PUBKEY (two readers of one key must agree), and the placeholder reds.
#
# Usage: scripts/package-release.sh [--out DIR] [--manifest FILE]
# Env:  RELEASE_TAG            the tag being packaged (asserted == the tree's VERSION, D6)
#       GESTION_REF            the old gestion ref the vendored apps come from (default: main)
#       GESTION_TREE           a gestion checkout to read the vendored apps from instead of cloning
#       GESTION_URL            override the gestion clone URL (tests)
#       REPO_TREE              the git tree to archive the suite half from (default: this repo)
#       MINISIGN_SECRET_KEY    the .sec key file's contents
#       MINISIGN_KEY_PASSWORD  the key's passphrase ("" for a passphrase-less key)
#
# Self-test: scripts/package-release.sh --self-test — hermetic: fixture trees + a throwaway
# keypair generated by the same signify; no network, no docker, no /opt writes.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GESTION_URL_DEFAULT="https://github.com/APS-Conecta/gestion.git"

die() { echo "FATAL: $*" >&2; exit 1; }
say()  { printf '  %s\n' "$*"; }

# ── self-test — fixture repos and a real throwaway keypair; no network, no root state ──
# shellcheck disable=SC2016,SC2034  # the check arms are eval'd single-quoted payloads; rc/sha1
#                                    # are read inside them, never here
if [ "${1:-}" = "--self-test" ]; then
  command -v signify >/dev/null 2>&1 || { echo "self-test: signify (signify-openbsd) missing — sudo apt-get install signify-openbsd" >&2; exit 1; }
  command -v git >/dev/null 2>&1       || { echo "self-test: git missing" >&2; exit 1; }
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  n=0; FAILED=0
  check() { n=$((n + 1)); if eval "$2"; then :; else echo "  FAIL: $1" >&2; FAILED=$((FAILED + 1)); fi; }

  # a real throwaway keypair — the sign/prove arms are real crypto, not shape asserts
  ( umask 077 && signify -G -n -p "$tmp/installer.pub" -s "$tmp/installer.sec" -c "self-test key" )

  # mk_repo DIR PUBFILE [REGISTER(0|1)] — a fixture suite repo tagged v9.8.7 carrying the assembly
  # contract and the suite's own theme, data and register; the constants carry the SAME trailing
  # comments the real install.sh ships (the seds are quote-scoped, not end-anchored — the arms must
  # test the real bytes)
  mk_repo() {
    rm -rf "$1"; mkdir -p "$1/host" "$1/sites" "$1/provisioning/data" "$1/themes/apsconecta"
    ( cd "$1" && git init -q && git config user.email self@test.invalid && git config user.name selftest
      printf 'v9.8.7\n' > VERSION
      printf '#!/usr/bin/env bash\ntrue\n' > host/aps-conecta
      printf '{"masters":[]}' > provisioning/data/packages.json
      printf 'theme\n' > themes/apsconecta/STYLE
      [ "${3:-1}" = 1 ] && printf 'r;establecimiento\n1;CESFAM Fixture\n' > sites/establecimientos-deis-2026.csv
      { echo '#!/usr/bin/env bash'
        echo 'BUNDLE_TAG="v0.0.0"             # fixture comment the real file carries'
        echo 'TARBALL_SHA256=""               # fixture comment the real file carries'
        printf 'SIGNIFY_PUBKEY="%s"  # fixture comment the real file carries\n' "$(sed -n 2p "$2")"
        echo '[ "${1:-}" = "--self-test" ] && exit 0'
        echo 'exit 0'; } > install.sh
      cp "$2" installer.pub
      python3 -c 'import json; print(json.dumps([{"id": f"app{i}", "source": "store", "optional": False, "containers": []} for i in range(1, 11)]))' > apps.json
      git add -A && git commit -qm fixture && git tag -f v9.8.7 )
  }
  # mk_gestion DIR N — the old gestion's vendored apps, plus decoys where the suite's own theme,
  # data and register live: the package must take those from the tag tree, never from here
  mk_gestion() {
    rm -rf "$1"; local i d
    mkdir -p "$1/sites" "$1/provisioning/data" "$1/themes/apsconecta"
    for i in $(seq 1 "$2"); do
      d="$1/provisioning/apps/app$i"; mkdir -p "$d"
      { echo "version=1.$i.0"; printf 'sha256=%s\n' "$(printf '0%.0s' $(seq 1 64))"
        echo "url=https://fixture.invalid/app$i.tar.gz"; } > "$d/VENDOR"
      printf 'app%d\n' "$i" > "$d/app$i.tar.gz"
    done
    printf 'decoy\n' > "$1/provisioning/data/decoy.json"
    printf 'decoy\n' > "$1/themes/apsconecta/STYLE"
    printf 'r;establecimiento\n' > "$1/sites/establecimientos-deis-1999.csv"
    return 0
  }
  # run_pkg OUT REPO SECKEY PW — one packaging pass; rc carries its status (a red dies inside the
  # subshell, never the test run — and $? is never read after check()'s own counter assignment)
  run_pkg() { rc=0
    ( RELEASE_TAG=v9.8.7 REPO_TREE="$2" GESTION_TREE="$tmp/gestion" \
        MINISIGN_SECRET_KEY="$(cat "$3")" MINISIGN_KEY_PASSWORD="$4" \
        bash "$REPO_ROOT/scripts/package-release.sh" --out "$1" ) >/dev/null 2>&1 || rc=$?
    return 0
  }

  mk_repo "$tmp/repo" "$tmp/installer.pub"
  mk_gestion "$tmp/gestion" 10
  run_pkg "$tmp/o1" "$tmp/repo" "$tmp/installer.sec" ""
  sha1="$(sha256sum "$tmp/o1/apsconecta-v9.8.7.tar.gz" 2>/dev/null | cut -d' ' -f1)"
  check "round trip: rc 0 and the four assets exist" \
    '[ "$rc" -eq 0 ] && [ -n "$sha1" ] && [ -f "$tmp/o1/SHA256SUMS" ] && [ -f "$tmp/o1/SHA256SUMS.minisig" ] && [ -f "$tmp/o1/apsconecta-v9.8.7-install.sh" ]'
  check "composite: the tag tree (install.sh's contract, theme, data, register) + the vendored apps at the package root" \
    'tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/host/aps-conecta$" \
      && tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/provisioning/apps/app1/VENDOR$" \
      && tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/provisioning/data/packages.json$" \
      && tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/sites/establecimientos-deis-2026.csv$" \
      && tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/themes/apsconecta/STYLE$" \
      && tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -q "^instalador/.paquete.json$"'
  check "only the vendored apps come from the old gestion — its theme, data and register never reach the package" \
    '[ "$(tar -xzOf "$tmp/o1/apsconecta-v9.8.7.tar.gz" instalador/themes/apsconecta/STYLE)" = theme ] \
      && ! tar -tzf "$tmp/o1/apsconecta-v9.8.7.tar.gz" | grep -qE "decoy|establecimientos-deis-1999"'
  check "SUMS shape: exactly the two-space line install.sh greps -qx, naming the tag's file" \
    '[ "$(cat "$tmp/o1/SHA256SUMS")" = "$sha1  apsconecta-v9.8.7.tar.gz" ]'
  check "proof: the signature verifies with the fixture pubkey — the same call the clinic runs" \
    '( cd "$tmp/o1" && signify -V -p "$tmp/installer.pub" -m SHA256SUMS -x SHA256SUMS.minisig )'
  check "asset: constants filled through the trailing comments — BUNDLE_TAG the tag, TARBALL_SHA256 the measured sha, the file executable" \
    '[ "$(sed -n "s/^BUNDLE_TAG=\"\([^\"]*\)\".*/\1/p" "$tmp/o1/apsconecta-v9.8.7-install.sh" | head -1)" = v9.8.7 ] \
      && [ "$(sed -n "s/^TARBALL_SHA256=\"\([^\"]*\)\".*/\1/p" "$tmp/o1/apsconecta-v9.8.7-install.sh" | head -1)" = "$sha1" ] \
      && [ -x "$tmp/o1/apsconecta-v9.8.7-install.sh" ]'

  run_pkg "$tmp/o2" "$tmp/repo" "$tmp/installer.sec" ""
  check "determinism: a second pass rebuilds the same bytes (any clone of the tag → one sha256)" \
    '[ "$rc" -eq 0 ] && [ "$(sha256sum "$tmp/o2/apsconecta-v9.8.7.tar.gz" | cut -d" " -f1)" = "$sha1" ]'

  ( cd "$tmp/repo" && printf 'v9.9.9\n' > VERSION && git add -A && git commit -qm drift && git tag -f v9.8.7 )
  run_pkg "$tmp/o3" "$tmp/repo" "$tmp/installer.sec" ""
  check "VERSION != tag reds (D6's assert — the release commit sets both), nothing packaged" \
    '[ "$rc" -ne 0 ] && [ ! -e "$tmp/o3/apsconecta-v9.8.7.tar.gz" ]'
  mk_repo "$tmp/repo" "$tmp/installer.pub"   # restore (flip-then-revert): the later arms read a clean repo

  printf 'untrusted comment: APS Conecta instalador release key (placeholder — aps/RELEASING.md replaces this)\nRWQf6LgoAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA\n' > "$tmp/placeholder.pub"
  mk_repo "$tmp/repo4" "$tmp/placeholder.pub"
  run_pkg "$tmp/o4" "$tmp/repo4" "$tmp/installer.sec" ""
  check "placeholder pubkey reds — the release gate reds on 'placeholder'" '[ "$rc" -ne 0 ]'

  mk_repo "$tmp/repo5" "$tmp/installer.pub"
  ( cd "$tmp/repo5" && sed -i 's|^SIGNIFY_PUBKEY=.*|SIGNIFY_PUBKEY="RWQf6LgoBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"|' install.sh \
      && git add -A && git commit -qm drift && git tag -f v9.8.7 )
  run_pkg "$tmp/o5" "$tmp/repo5" "$tmp/installer.sec" ""
  check "two readers disagree reds — installer.pub's key line == install.sh's SIGNIFY_PUBKEY" '[ "$rc" -ne 0 ]'

  mk_gestion "$tmp/gestion" 9
  run_pkg "$tmp/o6" "$tmp/repo" "$tmp/installer.sec" ""
  check "a manifest app without its VENDOR reds — the package ships every app apps.json lists" '[ "$rc" -ne 0 ]'
  mk_gestion "$tmp/gestion" 11
  run_pkg "$tmp/o6b" "$tmp/repo" "$tmp/installer.sec" ""
  check "a VENDOR dir outside the manifest reds — the package ships no app apps.json does not list" '[ "$rc" -ne 0 ]'
  mk_gestion "$tmp/gestion" 10
  mk_repo "$tmp/repo7" "$tmp/installer.pub" 0
  run_pkg "$tmp/o7" "$tmp/repo7" "$tmp/installer.sec" ""
  check "a tag tree without its register reds — an empty glob is a failure, never a green" '[ "$rc" -ne 0 ]'

  ( umask 077 && printf 'pw\n' | signify -G -p "$tmp/enc.pub" -s "$tmp/enc.sec" -c "self-test enc key" )
  mk_repo "$tmp/repo8" "$tmp/enc.pub"
  run_pkg "$tmp/o8" "$tmp/repo8" "$tmp/enc.sec" "pw"
  check "encrypted key: the passphrase rides stdin (signify's headless path) and the proof verifies" \
    '[ "$rc" -eq 0 ] && [ -f "$tmp/o8/SHA256SUMS.minisig" ] \
      && ( cd "$tmp/o8" && signify -V -p "$tmp/enc.pub" -m SHA256SUMS -x SHA256SUMS.minisig )'
  run_pkg "$tmp/o9" "$tmp/repo8" "$tmp/enc.sec" "wrong"
  check "wrong passphrase reds — the checksum names it, never a silent unsigned release" '[ "$rc" -ne 0 ]'

  rm -rf "$tmp"
  echo
  echo "self-test: $n checks OK"
  [ "$FAILED" -eq 0 ] || { echo "self-test: $FAILED FAILED" >&2; exit 1; }
  exit 0
fi

out="." manifest=""
while [ $# -gt 0 ]; do
  case "$1" in
    --out)      out="${2:?--out needs a value}"; shift 2 ;;
    --manifest) manifest="${2:?--manifest needs a value}"; shift 2 ;;
    *) die "usage: $0 [--out DIR] [--manifest FILE]  (env: RELEASE_TAG, GESTION_REF, GESTION_TREE, MINISIGN_SECRET_KEY, MINISIGN_KEY_PASSWORD)" ;;
  esac
done

command -v git >/dev/null 2>&1       || die "git missing on this runner"
command -v tar >/dev/null 2>&1       || die "tar missing on this runner"
command -v sha256sum >/dev/null 2>&1 || die "sha256sum missing on this runner"
command -v signify >/dev/null 2>&1   || die "signify (signify-openbsd) missing — sudo apt-get install -y signify-openbsd (the same package the clinic verifies with)"

tag="${RELEASE_TAG:?set RELEASE_TAG to the instalador tag being packaged}"
[[ "$tag" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$ ]] || die "tag '$tag' is not channel-valid (retag.sh's tag_valid shape — it names assets and a sed line)"
tree="${REPO_TREE:-$REPO_ROOT}"
gestion_ref="${GESTION_REF:-main}"

mkdir -p "$out"
[ -z "$(ls -A "$out" 2>/dev/null)" ] || die "--out ($out) is not empty — refusing to overwrite (bake into a clean dir)"

work="$(mktemp -d)" || die "mktemp failed"
trap 'rm -rf "$work"' EXIT
staging="$work/staging/instalador"
mkdir -p "$staging"

# 1 — the instalador half: the tag's tree, from git archive (never a working tree)
git -C "$tree" archive --format=tar "$tag" | tar -x -C "$staging" \
  || die "git archive $tag failed — run from a clone that carries the tag"

# 2 — the counted floors on the instalador half (D6's assert lives here, not in trust)
[ -f "$staging/VERSION" ] || die "the tag tree carries no VERSION — the release commit sets it (D6)"
ver="$(head -1 "$staging/VERSION")"
[ "$ver" = "$tag" ] || die "VERSION is '$ver' but the tag is '$tag' — the release commit sets both; refusing"
[ -f "$staging/host/aps-conecta" ] || die "the tag tree carries no host/aps-conecta — not a suite (install.sh's assembly contract)"
[ -f "$staging/install.sh" ] || die "the tag tree carries no install.sh — nothing to fill"
[ -f "$staging/installer.pub" ] || die "the tag tree carries no installer.pub — nothing to prove against"

# 3 — the pubkey gates: no placeholder signs a release; the two readers agree (quote-scoped
#     reads — the real constant lines carry trailing comments)
grep -qi 'placeholder' "$staging/installer.pub" \
  && die "installer.pub still carries the placeholder key — aps/RELEASING.md's keygen replaces it first; the release gate reds on 'placeholder'"
pub_line="$(sed -n 2p "$staging/installer.pub")"
emb_line="$(sed -n 's/^SIGNIFY_PUBKEY="\([^"]*\)".*/\1/p' "$staging/install.sh" | head -1)"
[ -n "$emb_line" ] || die "install.sh carries no SIGNIFY_PUBKEY constant"
[ "$pub_line" = "$emb_line" ] \
  || die "installer.pub's key line and install.sh's SIGNIFY_PUBKEY disagree — two readers of one key must agree (the env.sh lesson)"

# 4 — the vendored apps: the old gestion's provisioning/apps, sparse-cloned exactly like the bake
#     (the one part of the package not in the tag tree; #42 removes it)
if [ -n "${GESTION_TREE:-}" ]; then
  gestion="$GESTION_TREE"
else
  gestion="$work/gestion"
  git clone --depth 1 --filter=blob:none --sparse "${GESTION_URL:-$GESTION_URL_DEFAULT}" "$gestion" \
    || die "gestion clone failed"
  git -C "$gestion" sparse-checkout set provisioning/apps
  git -C "$gestion" fetch --depth 1 origin "$gestion_ref"
  git -C "$gestion" checkout FETCH_HEAD
fi
gestion_sha="$(git -C "$gestion" rev-parse HEAD 2>/dev/null || echo non-git-tree)"

# 5 — the vendored apps against the tag's suite manifest: one VENDOR per apps.json row, no other
#     app dir, every VENDOR well formed
apps="$(python3 "$REPO_ROOT/scripts/apps.py" --manifest "$staging/apps.json" ids)" \
  || die "the tag tree's suite manifest (apps.json) is unreadable — scripts/apps.py says why above"
bad_vendor=0
for d in "$gestion"/provisioning/apps/*/; do
  [ -d "$d" ] || continue
  printf '%s\n' "$apps" | grep -qxF -- "$(basename "$d")" \
    || { echo "provisioning/apps/$(basename "$d"): not in apps.json — the bake would ship an app the suite does not list" >&2; bad_vendor=1; }
done
for app in $apps; do
  v="$gestion/provisioning/apps/$app/VENDOR"
  [ -f "$v" ] || { echo "$app: listed in apps.json but provisioning/apps/$app/VENDOR is missing" >&2; bad_vendor=1; continue; }
  for k in version sha256 url; do
    grep -q "^$k=." "$v" || { echo "$v: no $k=" >&2; bad_vendor=1; }
  done
  grep -qE '^sha256=[0-9a-f]{64}$' "$v" || { echo "$v: sha256= is not a 64-hex digest" >&2; bad_vendor=1; }
  grep -qE '^sha256=<(measured|resolved)' "$v" && { echo "$v: a placeholder sha256 — UNPINNED is a bug, not a state" >&2; bad_vendor=1; }
done
[ "$bad_vendor" -eq 0 ] || die "the vendored apps do not match apps.json, or a VENDOR is malformed"
register=0
for _csv in "$staging"/sites/establecimientos-deis-*.csv; do
  [ -e "$_csv" ] && register=$((register + 1))
done
[ "$register" -eq 1 ] || die "expected exactly one sites/establecimientos-deis-*.csv in the tag tree, found $register"

# 6 — the overlay (identical paths, D11)
cp -a "$gestion/provisioning/apps" "$staging/provisioning/apps"

# 7 — provenance: .paquete.json inside the bundle root
manifest_sha=""
if [ -n "$manifest" ]; then
  [ -f "$manifest" ] || die "--manifest $manifest: no such file"
  manifest_sha="$(sha256sum "$manifest" | cut -d' ' -f1)"
fi
commit_ts="$(git -C "$tree" show -s --format=%ct "$tag" || die "cannot read the tag commit's date")"
python3 - "$tag" "$(git -C "$tree" rev-parse "$tag^{commit}")" "$gestion_ref" "$gestion_sha" "$manifest_sha" > "$staging/.paquete.json" <<'PY'
import json, sys
tag, isha, gref, gsha, msha = sys.argv[1:6]
pkg = {"release": tag, "instalador_sha": isha, "gestion_ref": gref, "gestion_sha": gsha}
if msha:
    pkg["images_manifest_sha256"] = msha
json.dump(pkg, sys.stdout, indent=2, sort_keys=True)
print()
PY

# 8 — the deterministic tarball
pkg="apsconecta-$tag.tar.gz"
tar --sort=name --mtime="@$commit_ts" --owner=0 --group=0 --numeric-owner --format=gnu \
    -c -C "$work/staging" instalador | gzip -n > "$out/$pkg" || die "packaging failed"
pkg_sha="$(sha256sum "$out/$pkg" | cut -d' ' -f1)"

# 9 — SHA256SUMS, the signature, the PROOF
printf '%s  %s\n' "$pkg_sha" "$pkg" > "$out/SHA256SUMS"
keydir="$work/keys"; ( umask 077 && mkdir -p "$keydir" )
seckey="$keydir/installer.sec"
[ -n "${MINISIGN_SECRET_KEY:-}" ] || die "MINISIGN_SECRET_KEY is empty — a release signs, always (aps/RELEASING.md)"
printf '%s\n' "$MINISIGN_SECRET_KEY" > "$seckey"
printf '%s\n' "${MINISIGN_KEY_PASSWORD:-}" | signify -S -s "$seckey" -m "$out/SHA256SUMS" -x "$out/SHA256SUMS.minisig" \
  || die "signing failed — the passphrase (MINISIGN_KEY_PASSWORD) or the key (MINISIGN_SECRET_KEY) is wrong"
rm -f "$seckey"
sed -i "1s|.*|untrusted comment: APS Conecta suite $tag $(date -u +%F)|" "$out/SHA256SUMS.minisig"
signify -V -p "$staging/installer.pub" -m "$out/SHA256SUMS" -x "$out/SHA256SUMS.minisig" \
  || die "the PROOF failed — the signature does not verify against the committed installer.pub (key rotation half-done? aps/RELEASING.md)"
( cd "$out" && sha256sum -c SHA256SUMS ) >/dev/null || die "SHA256SUMS does not verify the tarball beside it"

# 10 — the constants-filled install asset, proven in its final shape (quote-scoped fills: the
#      trailing comments on the constant lines survive, only the quoted values change)
sed -e "s|^BUNDLE_TAG=\"[^\"]*\"|BUNDLE_TAG=\"$tag\"|" \
    -e "s|^TARBALL_SHA256=\"[^\"]*\"|TARBALL_SHA256=\"$pkg_sha\"|" \
    "$staging/install.sh" > "$out/apsconecta-$tag-install.sh"
chmod 0755 "$out/apsconecta-$tag-install.sh"
[ "$(sed -n 's/^TARBALL_SHA256="\([^"]*\)".*/\1/p' "$out/apsconecta-$tag-install.sh" | head -1)" = "$pkg_sha" ] \
  || die "the install asset's TARBALL_SHA256 is not the measured sha — the fill drifted"
cp "$staging/installer.pub" "$out/installer.pub"   # the asset's self-test reads installer.pub beside it
bash "$out/apsconecta-$tag-install.sh" --self-test >/dev/null 2>&1 \
  || die "the filled install asset fails its own self-test"
rm -f "$out/installer.pub"

say "package:    $out/$pkg  sha256=$pkg_sha"
say "provenance: instalador $tag / gestion $gestion_sha ($gestion_ref)${manifest_sha:+ / manifest $manifest_sha}"
say "proof:      Signature Verified against the committed installer.pub; asset self-test green"
echo "PACKAGE: PASS — $tag assembled, signed, proven; assets in $out"
